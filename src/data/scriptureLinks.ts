export function chapterUrl(id: string, chapter: number): string | null {
  const book = getBook(id);
  if (
    !book ||
    !paths[id] ||
    !Number.isInteger(chapter) ||
    chapter < 1 ||
    chapter > book.chapters
  )
    return null;
  const collection = { old: "ot", new: "nt", bom: "bofm" }[book.testament];
  return `https://www.churchofjesuschrist.org/study/scriptures/${collection}/${paths[id]}/${chapter}?lang=por`;
}
