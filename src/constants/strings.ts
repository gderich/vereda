// Mensagens dinâmicas
export const getStreakMessage = (streak: number): string => {
  if (streak === 0) return 'Que tal começar hoje?';
  if (streak < 3) return `${streak} dia${streak > 1 ? 's' : ''} de leitura. Continue assim!`;
  if (streak < 7) return `${streak} dias de fé! Sua streak está crescendo.`;
  if (streak < 30) return `${streak} dias de sequência! Você é fiel.`;
  if (streak < 100) return `${streak} dias! Você é um verdadeiro leitor de escrituras.`;
  if (streak < 365) return `${streak} dias! Você é uma inspiração para muitos.`;
  return `${streak} dias! Você é um verdadeiro discípulo.`;
};

export const getXpMessage = (xp: number, level: number): string => {
  const nextLevelXP = level * 200;
  const xpForNext = nextLevelXP - (xp % nextLevelXP);
  if (xpForNext === 0) return 'Parabéns! Você subiu de nível!';
  return `Faltam ${xpForNext} XP para o próximo nível`;
};