"""Convert the publisher's PorAR 1.7 MySQL dump to an offline compressed payload.
Usage: python scripts/import-bible.py /path/to/pt_nar.sql
Source and redistribution statement: https://www.almeidarecebida.org/
No SQL is executed. Verse text is preserved, including the publisher's spelling.
"""
import sys,re,json,gzip,base64,hashlib
from pathlib import Path
source=Path(sys.argv[1]).read_bytes();text=source.decode('utf-8-sig')
rows=re.findall(r"\((\d+), (\d+), (\d+), (\d+), '((?:\\.|''|[^'\\])*)'\)",text,re.S)
assert len(rows)==31102, f'Unexpected verse count: {len(rows)}'
ids='gen exo lev num deu jos jdg rut 1sa 2sa 1ki 2ki 1ch 2ch ezr neh est job psa pro ecc son isa jer lam ezk dan hos joe amo oba jon mic nam hab zep hag zec mal mat mrk luk jhn act rom 1co 2co gal eph php col 1th 2th 1ti 2ti tit phm heb jas 1pe 2pe 1jn 2jn 3jn jud rev'.split()
books={}
for row,book,ch,v,verse in rows:
 verse=re.sub(r'\\(.)',lambda m:{'n':'\n','r':'\r','t':'\t','0':'\0'}.get(m[1],m[1]),verse)
 verse=verse.replace("''", "'")
 chapters=books.setdefault(ids[int(book)-1],{})
 verses=chapters.setdefault(ch,[])
 assert int(v)==len(verses)+1
 verses.append(verse)
assert len(books)==66 and sum(map(len,books.values()))==1189
payload=base64.b64encode(gzip.compress(json.dumps(books,ensure_ascii=False,separators=(',',':')).encode(),mtime=0)).decode()
Path('src/data/biblePayload.ts').write_text('// Almeida Recebida 1.7. See BIBLE-SOURCE.md. Generated by scripts/import-bible.py.\nexport default '+json.dumps(payload)+';\n')
print(json.dumps({'books':len(books),'chapters':sum(map(len,books.values())),'verses':len(rows),'sourceSha256':hashlib.sha256(source).hexdigest(),'payloadBytes':len(payload)}))
